static int evaluate(int row, const int *u) {
    int cursor=0, total=equations[row][cursor++];
    for(int i=0;i<10;++i) total += equations[row][cursor++]*u[i];
    for(int i=0;i<10;++i) total += equations[row][cursor++]*u[i]*u[i];
    for(int i=0;i<10;++i)
        for(int j=i+1;j<10;++j)
            total += equations[row][cursor++]*u[i]*u[j];
    total %= P;
    return total < 0 ? total + P : total;
}

int main(int argc, char **argv) {
    if(argc!=6){fprintf(stderr,"usage: %s u0 u6 u7 u8 u9\n",argv[0]);return 64;}
    int u[10]={0};
    u[0]=atoi(argv[1])%P; u[6]=atoi(argv[2])%P; u[7]=atoi(argv[3])%P;
    u[8]=atoi(argv[4])%P; u[9]=atoi(argv[5])%P;
    long tested=0, solutions=0;
    for(u[1]=0;u[1]<P;++u[1])
    for(u[2]=0;u[2]<P;++u[2])
    for(u[3]=0;u[3]<P;++u[3])
    for(u[4]=0;u[4]<P;++u[4])
    for(u[5]=0;u[5]<P;++u[5]) {
        ++tested;
        int valid=1;
        for(int row=0;row<9;++row) if(evaluate(row,u)){valid=0;break;}
        if(valid){
            ++solutions;
            printf("solution u=[%d,%d,%d,%d,%d,%d,%d,%d,%d,%d]\n",
                   u[0],u[1],u[2],u[3],u[4],u[5],u[6],u[7],u[8],u[9]);
        }
    }
    printf("tested=%ld solutions=%ld\n",tested,solutions);
    return 0;
}
